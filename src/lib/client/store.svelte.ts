const SAVE_DEBOUNCE_MS = 300;
const REFRESH_DEBOUNCE_MS = 250;
const STATUS_RESET_MS = 3000;
const EVENTS_URL = "/api/events";

type Written = Promise<{ revision: number }>;

/** The create/update/remove actions of one collection, as generated by `collectionActions` on the server. */
interface RemoteCollection {
    create: { orThrow(item: never): Written };
    update: { orThrow(input: { key: string; item: never }): Written };
    remove: { orThrow(input: { key: string }): Written };
}

// The generated action types differ per collection; the store passes items it built from the same domain types
const REMOTE: Record<CollectionKey | "labels" | "shapes" | "floors", RemoteCollection> = actions as unknown as
    Record<CollectionKey | "labels" | "shapes" | "floors", RemoteCollection>;

export interface CollectionActions<T extends Identifiable> {
    /** Uses `item.id` when given, otherwise generates one. */
    add(item: NewItem<T>): void;

    /** For exhibitors `patch.id` may rename the item; talks and booths follow. */
    update(id: Id, patch: Partial<T>): void;

    remove(id: Id): void;
}

export interface FloorItemActions<T extends Identifiable> {
    add(floorId: Id, item: NewItem<T>): void;

    update(floorId: Id, id: Id, patch: Partial<T>): void;

    remove(floorId: Id, id: Id): void;
}

export interface DataActions {
    updateEvent(patch: Partial<EventInfo>): void;

    categories: CollectionActions<CollectionItem<"categories">>;
    groups: CollectionActions<CollectionItem<"groups">>;
    exhibitors: CollectionActions<CollectionItem<"exhibitors">>;
    rooms: CollectionActions<CollectionItem<"rooms">>;
    talks: CollectionActions<CollectionItem<"talks">>;
    tracks: CollectionActions<CollectionItem<"tracks">>;
    classes: CollectionActions<CollectionItem<"classes">>;
    timeSlots: CollectionActions<CollectionItem<"timeSlots">>;

    floors: {
        add(label?: string, id?: Id): void;
        update(id: Id, patch: Partial<Pick<Floor, "label" | "width" | "height">>): void;
        remove(id: Id): void;
    };

    booths: {
        /** Places the exhibitor on `floorId`, moving it off any other floor. */
        place(floorId: Id, exhibitorId: Id, patch: Partial<Booth>): void;
        remove(exhibitorId: Id): void;
    };

    labels: FloorItemActions<FloorLabel>;
    shapes: FloorItemActions<FloorShape>;

    schedule: {
        set(classId: Id, timeSlotId: Id, zoneId: Id, value: ScheduleEntryType | null): void;
    };
}

/**
 * Client-side copy of the fair data. Writes are applied optimistically and sent as Astro actions in order;
 * after errors or changes by other admins the store reloads the server state.
 */
export class FairStore {
    data: AppData = $state.raw({} as AppData);
    saveStatus: SaveStatus = $state("idle");
    /** The message of the last failed write, until dismissed. */
    error: string | null = $state(null);
    /** Whether the live connection to the server is currently lost. */
    offline = $state(false);
    readonly actions: DataActions;

    #revision: number;
    #remoteRevision: number;
    /** Set when a write failed, so the optimistic state must be replaced by the server state. */
    #stale = false;
    readonly #queue: MutationQueue;
    #refreshTimer: ReturnType<typeof setTimeout> | undefined;
    #statusTimer: ReturnType<typeof setTimeout> | undefined;

    constructor(snapshot: Snapshot) {
        this.data = snapshot.data;
        this.#revision = snapshot.revision;
        this.#remoteRevision = snapshot.revision;
        this.#queue = new MutationQueue({
            debounceMs: SAVE_DEBOUNCE_MS,
            onStart: () => this.#setStatus("saving"),
            onWritten: (revision) => this.#onWritten(revision),
            onError: (cause) => this.#onError(cause),
            onIdle: () => this.#onIdle(),
        });
        this.actions = createActions(this);
    }

    /** Applies `action` locally and queues the server write derived from the resulting data under `key`. */
    commit(action: DataAction, key: string, write: ((data: AppData) => Written) | null): void {
        this.data = dataReducer(this.data, action);
        if (write) {
            const data = this.data;
            this.#queue.enqueue({ key, run: () => write(data) });
        }
    }

    /** Sends pending writes now, e.g. before navigating away. */
    flush(): Promise<void> {
        return this.#queue.flush();
    }

    /** Opens the live connection; returns the cleanup function. Call from an effect, never during SSR. */
    connect(): () => void {
        let source: EventSource | null = null;
        const open = () => {
            source?.close();
            source = new EventSource(EVENTS_URL);
            source.addEventListener("open", () => (this.offline = false));
            source.addEventListener("error", () => (this.offline = source?.readyState !== EventSource.OPEN));
            source.addEventListener("revision", (event) => this.#onRemoteRevision(Number(event.data)));
        };
        // Pending writes would be lost when the page goes away, so send them and let the browser ask
        const onBeforeUnload = (event: BeforeUnloadEvent) => {
            if (!this.#queue.busy) {
                return;
            }
            void this.flush();
            event.preventDefault();
        };
        const onPageHide = () => source?.close();
        const onPageShow = (event: PageTransitionEvent) => {
            if (event.persisted) {
                open();
            }
        };

        open();
        window.addEventListener("beforeunload", onBeforeUnload);
        window.addEventListener("pagehide", onPageHide);
        window.addEventListener("pageshow", onPageShow);
        return () => {
            source?.close();
            window.removeEventListener("beforeunload", onBeforeUnload);
            window.removeEventListener("pagehide", onPageHide);
            window.removeEventListener("pageshow", onPageShow);
            clearTimeout(this.#refreshTimer);
            clearTimeout(this.#statusTimer);
        };
    }

    /** Replaces all content with a backup file; throws with a German message on failure. */
    async importBackup(file: File): Promise<void> {
        await this.flush();
        try {
            this.#apply(await restoreBackup(file));
        } catch (cause) {
            throw new Error(errorMessage(cause), { cause });
        }
    }

    dismissError(): void {
        this.error = null;
    }

    async refresh(): Promise<void> {
        try {
            const snapshot = await fetchSnapshot();
            // Local edits made meanwhile would be overwritten; the idle handler refreshes again afterwards
            if (!this.#queue.busy) {
                this.#apply(snapshot);
            }
        } catch {
            this.offline = true;
        }
    }

    #apply(snapshot: Snapshot): void {
        this.data = snapshot.data;
        this.#revision = snapshot.revision;
        this.#remoteRevision = Math.max(this.#remoteRevision, snapshot.revision);
    }

    #onRemoteRevision(revision: number): void {
        this.#remoteRevision = Math.max(this.#remoteRevision, revision);
        if (revision > this.#revision && !this.#queue.busy) {
            clearTimeout(this.#refreshTimer);
            this.#refreshTimer = setTimeout(() => void this.refresh(), REFRESH_DEBOUNCE_MS);
        }
    }

    // Only the direct successor is ours alone; a gap means another admin wrote in between
    #onWritten(revision: number): void {
        if (revision === this.#revision + 1) {
            this.#revision = revision;
        }
        this.#remoteRevision = Math.max(this.#remoteRevision, revision);
    }

    #onError(cause: unknown): void {
        if (isSessionExpired(cause)) {
            this.#setStatus("session_expired");
            return;
        }
        this.error = errorMessage(cause);
        this.#setStatus("error");
        this.#stale = true;
    }

    #onIdle(): void {
        if (this.saveStatus === "saving") {
            this.#setStatus("saved");
        }
        if (this.saveStatus === "session_expired") {
            return;
        }
        if (this.#stale || this.#remoteRevision > this.#revision) {
            this.#stale = false;
            void this.refresh();
        }
    }

    #setStatus(status: SaveStatus): void {
        this.saveStatus = status;
        clearTimeout(this.#statusTimer);
        if (status === "saved") {
            this.#statusTimer = setTimeout(() => (this.saveStatus = "idle"), STATUS_RESET_MS);
        }
    }
}

function collectionActions<K extends CollectionKey>(store: FairStore, collection: K): CollectionActions<CollectionItem<K>> {
    const remote = REMOTE[collection];
    const find = (data: AppData, id: Id) => (data[collection] as Identifiable[]).find((item) => item.id === id) as never;

    return {
        add(item) {
            const id = item.id || createId();
            store.commit({ type: "collection/add", collection, item: { ...item, id } } as DataAction, `${collection}/${id}/create`,
                (data) => remote.create.orThrow(find(data, id)));
        },
        update(id, patch) {
            const nextId = (patch as Partial<Identifiable>).id ?? id;
            if (collection === "exhibitors" && nextId !== id) {
                store.commit({ type: "exhibitor/rename", id, nextId }, "", null);
            }
            store.commit({ type: "collection/update", collection, id: nextId, patch } as DataAction, `${collection}/${id}/update`,
                (data) => remote.update.orThrow({ key: id, item: find(data, nextId) }));
        },
        remove(id) {
            store.commit({ type: "collection/remove", collection, id } as DataAction, `${collection}/${id}/remove`,
                () => remote.remove.orThrow({ key: id }));
        },
    };
}

function floorItemActions<T extends FloorLabel | FloorShape>(store: FairStore, collection: "labels" | "shapes"): FloorItemActions<T> {
    const remote = REMOTE[collection];
    const find = (data: AppData, floorId: Id, id: Id) => {
        const item = data.floorPlan.floors.find((floor) => floor.id === floorId)?.[collection].find((entry) => entry.id === id);
        return { ...item, floorId } as never;
    };

    return {
        add(floorId, item) {
            const id = item.id || createId();
            store.commit({ type: "floorItem/add", collection, floorId, item: { ...item, id } } as DataAction, `${collection}/${id}/create`,
                (data) => remote.create.orThrow(find(data, floorId, id)));
        },
        update(floorId, id, patch) {
            store.commit({ type: "floorItem/update", collection, floorId, id, patch } as DataAction, `${collection}/${id}/update`,
                (data) => remote.update.orThrow({ key: id, item: find(data, floorId, id) }));
        },
        remove(floorId, id) {
            store.commit({ type: "floorItem/remove", collection, floorId, id } as DataAction, `${collection}/${id}/remove`,
                () => remote.remove.orThrow({ key: id }));
        },
    };
}

function floorRecord(data: AppData, id: Id) {
    const floor = data.floorPlan.floors.find((item) => item.id === id);
    return { id, label: floor?.label, width: floor?.width, height: floor?.height } as never;
}

function createActions(store: FairStore): DataActions {
    return {
        updateEvent(patch) {
            store.commit({ type: "event/update", patch }, "event/update", (data) => actions.event.update.orThrow(data.event));
        },

        categories: collectionActions(store, "categories"),
        groups: collectionActions(store, "groups"),
        exhibitors: collectionActions(store, "exhibitors"),
        rooms: collectionActions(store, "rooms"),
        talks: collectionActions(store, "talks"),
        tracks: collectionActions(store, "tracks"),
        classes: collectionActions(store, "classes"),
        timeSlots: collectionActions(store, "timeSlots"),

        floors: {
            add(label, id = createId()) {
                store.commit({ type: "floor/add", label, id }, `floors/${id}/create`, (data) => REMOTE.floors.create.orThrow(floorRecord(data, id)));
            },
            update(id, patch) {
                store.commit({ type: "floor/update", id, patch }, `floors/${id}/update`,
                    (data) => REMOTE.floors.update.orThrow({ key: id, item: floorRecord(data, id) }));
            },
            remove(id) {
                store.commit({ type: "floor/remove", id }, `floors/${id}/remove`, () => REMOTE.floors.remove.orThrow({ key: id }));
            },
        },

        booths: {
            place(floorId, exhibitorId, patch) {
                store.commit({ type: "booth/place", floorId, exhibitorId, patch }, `booths/${exhibitorId}/place`, (data) => {
                    const placed = findBooth(data.floorPlan, exhibitorId);
                    return actions.booths.place.orThrow({ ...placed!.booth, floorId });
                });
            },
            remove(exhibitorId) {
                store.commit({ type: "booth/remove", exhibitorId }, `booths/${exhibitorId}/remove`,
                    () => actions.booths.remove.orThrow({ key: exhibitorId }));
            },
        },

        labels: floorItemActions<FloorLabel>(store, "labels"),
        shapes: floorItemActions<FloorShape>(store, "shapes"),

        schedule: {
            set(classId, timeSlotId, zoneId, value) {
                store.commit({ type: "schedule/set", classId, timeSlotId, zoneId, value },
                    `schedule/${scheduleEntryId(classId, timeSlotId, zoneId)}`,
                    () => actions.schedule.set.orThrow({ classId, timeSlotId, zoneId, type: value }));
            },
        },
    };
}

const [getStore, setStore] = createContext<FairStore>();

